// Generates public/tests.js: runs every reference solution on its inputs to produce the expected outputs,
// checks each reference passes its own comparator, and checks every quest in logic.js has tests.
// Usage: node tests-src/build.mjs
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import problems from './problems.mjs';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const ctx = { console };
ctx.globalThis = ctx;
vm.createContext(ctx);
for (const f of ['public/judge-core.js', 'public/runtime.js', 'public/logic.js']) {
  vm.runInContext(fs.readFileSync(path.join(root, f), 'utf8') + (f.endsWith('logic.js') ? '\n;globalThis.PROBLEMS = PROBLEMS;' : ''), ctx, { filename: f });
}
const J = ctx.JudgeCore;

const titles = new Set(ctx.PROBLEMS.map((p) => p.title));
const out = {};
const refs = {};
let failures = 0;

for (const p of problems) {
  if (!titles.has(p.title)) { console.error('No quest named', p.title); failures++; continue; }
  if (out[p.title]) { console.error('Duplicate tests for', p.title); failures++; continue; }
  const spec = { fn: p.fn, kind: p.kind || 'fn' };
  for (const k of ['in', 'out', 'mutate', 'prefix', 'compare']) if (p[k] !== undefined) spec[k] = p[k];
  spec.cases = p.cases.map((c) => (spec.kind === 'design'
    ? { ops: c.ops, args: c.args, expected: J.computeDesign(p.ref, c.ops, c.args) }
    : { args: c, expected: J.computeExpected(spec, p.ref, c) }));
  // The reference must pass its own tests through the same path the browser uses.
  spec.cases.forEach((c, i) => {
    const r = J.runCase(spec, p.ref, c);
    if (!r.ok) { console.error(`Reference fails ${p.title} case ${i + 1}:`, r); failures++; }
  });
  out[p.title] = spec;
  refs[p.title] = p.ref.toString();
}
for (const t of titles) if (!out[t]) { console.error('Missing tests for', t); failures++; }

if (failures) { console.error(failures + ' problem(s).'); process.exit(1); }

fs.writeFileSync(path.join(root, 'public/tests.js'),
  '// Generated by tests-src/build.mjs. Do not edit by hand.\n' +
  'self.STEPWISE_TESTS = ' + JSON.stringify(out) + ';\n');
fs.writeFileSync(path.join(root, 'tests-src/refs.json'), JSON.stringify(refs, null, 1));
const total = Object.values(out).reduce((n, s) => n + s.cases.length, 0);
console.log(`Wrote tests for ${Object.keys(out).length} quests, ${total} cases.`);
